"""Fixed, reviewed interface text for translated reports.

Screen labels ("Result", "Reported range", disclaimers, ...) and the standard
"discuss with your doctor" bullets never depend on the report, so they are NOT
generated by an AI model. They used to be: the first model call had to return
all 78 labels in the right script and one missing/English label failed the whole
translation, wasting quota and showing the user "translation unavailable".

Now only the report's own content (summaries, finding explanations, medication
phrasing, test names) goes to a model. Everything here is deterministic,
instant, free and identical on every request.

The table lives in ``translation_ui_labels.json`` (language code -> key -> text).
It was drafted for this app; have a native speaker of each language review it
before a public release (see AUDIT_REPORT.md).
"""

from __future__ import annotations

import json
import logging
import re
from functools import lru_cache
from pathlib import Path
from typing import Any, Iterable

logger = logging.getLogger(__name__)

_LABELS_PATH = Path(__file__).with_name("translation_ui_labels.json")

# Keys in the table that are templates, not screen labels.
_TEMPLATE_KEYS = {"dp_abnormal"}


@lru_cache(maxsize=1)
def _table() -> dict[str, dict[str, str]]:
    return json.loads(_LABELS_PATH.read_text(encoding="utf-8"))


def supported_languages() -> list[str]:
    return [code for code in _table() if code != "en"]


def get_ui_labels(language: str) -> dict[str, str]:
    """Every screen label for ``language``.

    A key missing from a language falls back to English rather than raising, so
    the app can never show a blank label.
    """
    table = _table()
    english = table["en"]
    chosen = table.get((language or "").lower().split("-")[0], english)
    return {
        key: chosen.get(key) or english[key]
        for key in english
        if key not in _TEMPLATE_KEYS
    }


_FLAG_LABEL = {
    "HIGH": "label_high",
    "H": "label_high",
    "LOW": "label_low",
    "L": "label_low",
    "CRITICAL": "label_critical",
    "CRITICAL_HIGH": "label_critical",
    "CRITICAL_LOW": "label_critical",
    "ABNORMAL": "chip_noteworthy",
}


def _clean(text: str) -> str:
    text = re.sub(r"\(\s+", "(", text)
    text = re.sub(r"\s+\)", ")", text)
    text = re.sub(r"\(\s*\)", "", text)
    return re.sub(r"[ \t]{2,}", " ", text).strip()


def build_discussion_points(
    language: str,
    findings: Iterable[dict[str, Any]],
    translated_names: dict[str, str] | None = None,
    *,
    has_medications: bool,
    max_points: int = 5,
) -> list[str]:
    """Doctor-discussion bullets built from templates (no model involved).

    Follows the same rules the old prompt asked a model to follow:
    one bullet for each of the first three out-of-range results, otherwise one
    "review your results" bullet; one medication bullet (confirm dose/timing,
    or ask about new medication); and always one follow-up bullet.
    """
    table = _table()
    english = table["en"]
    lang = table.get((language or "").lower().split("-")[0], english)
    labels = get_ui_labels(language)
    translated_names = translated_names or {}

    def label_text(key: str) -> str:
        return labels.get(key) or english[key]

    template = lang.get("dp_abnormal") or english["dp_abnormal"]
    points: list[str] = []
    for finding in findings:
        if len(points) >= 3:
            break
        if not isinstance(finding, dict):
            continue
        flag = str(finding.get("flag") or "").strip().upper().replace(" ", "_")
        label_key = _FLAG_LABEL.get(flag)
        if not label_key:
            continue
        name = str(finding.get("test_name") or finding.get("parameter") or "").strip()
        if not name:
            continue
        shown_name = translated_names.get(name) or name
        value = finding.get("value")
        unit = finding.get("unit")
        points.append(
            _clean(
                template.format(
                    test=shown_name,
                    flag=label_text(label_key),
                    value="" if value is None else str(value),
                    unit="" if unit is None else str(unit),
                )
            )
        )

    if not points:
        points.append(label_text("label_review_test_parameters"))
    points.append(
        label_text(
            "label_confirm_dosage_timing"
            if has_medications
            else "label_confirm_new_medications"
        )
    )
    points.append(label_text("label_confirm_followup"))
    return points[:max_points]
